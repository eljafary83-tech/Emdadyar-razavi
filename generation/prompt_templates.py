# --------------------------------------------------------------------------- #
# نگاشت نوع درخواست به قالب متناظر
# --------------------------------------------------------------------------- #
_TEMPLATE_MAP = {
    RequestType.QA: QA_TEMPLATE,
    RequestType.SCENARIO: SCENARIO_TEMPLATE,
    RequestType.QUIZ: QUIZ_TEMPLATE,
}


def get_prompt_template(request_type: RequestType) -> str:
    """
    بازگرداندن قالب Prompt خام (بدون پرکردن placeholderها) متناظر با نوع درخواست.

    Args:
        request_type: نوع درخواست تشخیص داده‌شده توسط IntentClassifier.

    Returns:
        رشته قالب Prompt حاوی placeholderهای {common_rules}, {context},
        {user_input} و در حالت QUIZ همچنین {num_questions}.

    Raises:
        ValueError: اگر request_type مقداری خارج از RequestType باشد.
    """
    template = _TEMPLATE_MAP.get(request_type)
    if template is None:
        raise ValueError(f"نوع درخواست پشتیبانی‌نشده: {request_type}")
    return template
